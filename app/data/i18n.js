export function getStrings(lang) {
  return STRINGS[lang === 'id' ? 'id' : 'en'];
}

export function closeMobileNav() {
  const nav = document.getElementById('primary-nav');
  const btn = document.getElementById('nav-toggle');
  nav?.classList.remove('open');
  btn?.setAttribute('aria-expanded', 'false');
}

export function wireChromeControls({ getLang, toggleLang }) {
  const nav = document.getElementById('primary-nav');
  const toggleBtn = document.getElementById('nav-toggle');
  const searchForm = document.getElementById('quick-search');
  const searchInput = document.getElementById('quick-search-input');
  const langBtn = document.getElementById('lang-toggle');

  toggleBtn?.addEventListener('click', () => {
    const on = nav.classList.toggle('open');
    toggleBtn.setAttribute('aria-expanded', String(on));
  });

  searchForm?.addEventListener('submit', (ev) => {
    ev.preventDefault();
    const q = searchInput.value.trim();
    const lang = getLang();
    const p = lang === 'id' ? 'lang=id&' : '';
    location.hash = q ? `#/explorer?${p}q=${encodeURIComponent(q)}` : `#/explorer${lang === 'id' ? '?lang=id' : ''}`;
  });

  langBtn?.addEventListener('click', toggleLang);
}

export function applyChromeLabels(lang) {
  const s = getStrings(lang);
  document.documentElement.lang = lang === 'id' ? 'id' : 'en';
  const topOrg = document.getElementById('top-org');
  const topMeta = document.getElementById('top-meta');
  const brandSub = document.getElementById('brand-sub');
  const searchInp = document.getElementById('quick-search-input');
  const searchBtn = document.getElementById('search-btn');
  const navToggle = document.getElementById('nav-toggle');
  const langBtn = document.getElementById('lang-toggle');
  const footerCopy = document.getElementById('footer-copy');
  if (topOrg) topOrg.innerHTML = s.topOrg;
  if (topMeta) topMeta.textContent = s.topMeta;
  if (brandSub) brandSub.textContent = s.brandSub;
  if (searchInp) searchInp.placeholder = s.searchPlaceholder;
  if (searchBtn) searchBtn.textContent = s.searchBtn;
  if (navToggle) navToggle.textContent = s.menu;
  if (footerCopy) footerCopy.innerHTML = s.footerCopy;
  if (langBtn) {
    langBtn.innerHTML = lang === 'en' ? '<strong>EN</strong> | ID' : 'EN | <strong>ID</strong>';
  }
  document.querySelectorAll('[data-route]').forEach((el) => {
    const key = el.dataset.route;
    if (s.nav[key]) el.textContent = s.nav[key];
  });
}
